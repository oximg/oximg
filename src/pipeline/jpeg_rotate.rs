//! Lossless JPEG rotation for `strip --auto-rotate` (#163): the EXIF
//! orientation is applied to the DCT coefficients, as `jpegtran
//! -perfect` does, so the stored pixels come out upright with no
//! re-encode and the orientation tag can go.
//!
//! Every 8x8 block is moved and its coefficients transposed or
//! sign-flipped; quantization is untouched, so nothing is lost. That
//! is only exact when the edges the transform moves are whole iMCUs
//! (8 or 16 px, by chroma subsampling): a partial edge block cannot be
//! moved without its padding showing. Such a file, or one libjpeg
//! reads only with warnings (a truncated or corrupt scan would come
//! out "repaired" with grey fill), is left as it was, with the reason,
//! and the strip keeps its orientation tag instead.
//!
//! The work is libjpeg's own (`transupp.c`, vendored by mozjpeg-sys
//! behind its `jpegtran` feature); this module drives it.

use super::jpeg_dec::error_exit;
use crate::meta::Orientation;
use mozjpeg_sys as ffi;
use std::mem;
use std::os::raw::{c_int, c_ulong};

/// What [`rotate`] did.
pub(super) enum Rotation {
    /// The upright JPEG.
    Rotated(Vec<u8>),
    /// Not rotated, and why: the caller keeps the orientation tag.
    Kept(String),
}

/// How the source was coded, read from its markers by the strip walk
/// (libjpeg keeps these fields private).
pub(super) struct Coding {
    /// SOF2: written back progressive, else baseline.
    pub progressive: bool,
    /// A JFIF APP0 survived the strip: written back, else none.
    pub jfif: bool,
}

/// Apply `o` to a stripped JPEG's coefficients. ICC profile segments
/// (APP2) are carried over; every other marker the strip kept is
/// regenerated by libjpeg (JFIF, Adobe) or is the orientation EXIF this
/// replaces. `max_pixels` bounds the coefficient memory, about 2 bytes
/// per sample, twice over for the transposing transforms' workspace.
pub(super) fn rotate(jpeg: &[u8], o: Orientation, coding: &Coding, max_pixels: u64) -> Rotation {
    let run = crate::panic_guard::catch_unwind_as_error("JPEG rotation", || {
        // SAFETY: every libjpeg call below follows jpegtran's sequence
        // on structs this function owns; a fatal error unwinds out of
        // error_exit and the guards destroy both structs.
        unsafe { rotate_unguarded(jpeg, o, coding, max_pixels) }
    });
    match run {
        Ok(r) => r,
        Err(e) => Rotation::Kept(e.to_string()),
    }
}

fn transform_code(o: Orientation) -> ffi::JXFORM_CODE {
    match o.value() {
        2 => ffi::JXFORM_CODE_JXFORM_FLIP_H,
        3 => ffi::JXFORM_CODE_JXFORM_ROT_180,
        4 => ffi::JXFORM_CODE_JXFORM_FLIP_V,
        5 => ffi::JXFORM_CODE_JXFORM_TRANSPOSE,
        6 => ffi::JXFORM_CODE_JXFORM_ROT_90,
        7 => ffi::JXFORM_CODE_JXFORM_TRANSVERSE,
        8 => ffi::JXFORM_CODE_JXFORM_ROT_270,
        _ => ffi::JXFORM_CODE_JXFORM_NONE,
    }
}

/// `jpeg_transform_info` as the vendored `transupp.h` declares it.
/// mozjpeg-sys 2.2's binding of it predates the drop fields (the two
/// pointers after the crop parameters, `drop_width` / `drop_height`),
/// so it is 24 bytes short of the C struct, and transupp writing the
/// trailing fields through it overran whatever followed. The extern
/// functions take a raw pointer, so this layout is passed by cast.
#[repr(C)]
struct TransformInfo {
    transform: ffi::JXFORM_CODE,
    perfect: ffi::boolean,
    trim: ffi::boolean,
    force_grayscale: ffi::boolean,
    crop: ffi::boolean,
    slow_hflip: ffi::boolean,
    crop_width: ffi::JDIMENSION,
    crop_width_set: ffi::JCROP_CODE,
    crop_height: ffi::JDIMENSION,
    crop_height_set: ffi::JCROP_CODE,
    crop_xoffset: ffi::JDIMENSION,
    crop_xoffset_set: ffi::JCROP_CODE,
    crop_yoffset: ffi::JDIMENSION,
    crop_yoffset_set: ffi::JCROP_CODE,
    drop_ptr: *mut ffi::jpeg_decompress_struct,
    drop_coef_arrays: *mut ffi::jvirt_barray_ptr,
    num_components: c_int,
    workspace_coef_arrays: *mut ffi::jvirt_barray_ptr,
    output_width: ffi::JDIMENSION,
    output_height: ffi::JDIMENSION,
    x_crop_offset: ffi::JDIMENSION,
    y_crop_offset: ffi::JDIMENSION,
    drop_width: ffi::JDIMENSION,
    drop_height: ffi::JDIMENSION,
    i_mcu_sample_width: c_int,
    i_mcu_sample_height: c_int,
}

/// The transform info with a canary after it: a future vendored struct
/// that grows again is caught as a failed rotation, not a corruption
/// nobody sees.
#[repr(C)]
struct Guarded {
    info: TransformInfo,
    canary: [u8; CANARY_LEN],
}

const CANARY_LEN: usize = 64;
const CANARY: u8 = 0xA5;

impl Guarded {
    fn ffi(&mut self) -> *mut ffi::jpeg_transform_info {
        std::ptr::addr_of_mut!(self.info).cast()
    }

    fn intact(&self) -> bool {
        self.canary.iter().all(|&b| b == CANARY)
    }
}

/// A libjpeg error manager whose warnings are counted, not printed:
/// any warning means the coefficients are not what the file says.
fn error_mgr() -> Box<ffi::jpeg_error_mgr> {
    // SAFETY: all-zero is the state jpeg_std_error fills in.
    let mut err: Box<ffi::jpeg_error_mgr> = Box::new(unsafe { mem::zeroed() });
    unsafe { ffi::jpeg_std_error(&mut err) };
    err.error_exit = Some(error_exit);
    err.emit_message = Some(count_warning);
    err
}

unsafe extern "C-unwind" fn count_warning(cinfo: &mut ffi::jpeg_common_struct, level: c_int) {
    if level < 0 {
        // SAFETY: cinfo.err is the manager error_mgr built.
        unsafe { (*cinfo.err).num_warnings += 1 };
    }
}

struct Decompress {
    cinfo: Box<ffi::jpeg_decompress_struct>,
    _err: Box<ffi::jpeg_error_mgr>,
}

impl Drop for Decompress {
    fn drop(&mut self) {
        // SAFETY: created in rotate_unguarded; destroy frees what the
        // memory manager recorded, coefficient arrays included.
        unsafe { ffi::jpeg_destroy_decompress(&mut self.cinfo) };
    }
}

struct Compress {
    cinfo: Box<ffi::jpeg_compress_struct>,
    _err: Box<ffi::jpeg_error_mgr>,
    dest: Box<Dest>,
}

impl Drop for Compress {
    fn drop(&mut self) {
        // SAFETY: as for Decompress. `dest` outlives the struct.
        unsafe { ffi::jpeg_destroy_compress(&mut self.cinfo) };
    }
}

/// A `jpeg_destination_mgr` appending to a Vec.
#[repr(C)]
struct Dest {
    iface: ffi::jpeg_destination_mgr,
    out: Vec<u8>,
}

const DEST_CHUNK: usize = 64 << 10;

impl Dest {
    /// cinfo.dest is always this module's Dest: it is set only here.
    unsafe fn from_cinfo<'s>(cinfo: &mut ffi::jpeg_compress_struct) -> &'s mut Self {
        unsafe { &mut *cinfo.dest.cast::<Self>() }
    }

    /// Make room for another chunk past what is written.
    fn grow(&mut self) {
        let used = self.out.len();
        self.out.resize(used + DEST_CHUNK, 0);
        self.iface.next_output_byte = self.out[used..].as_mut_ptr();
        self.iface.free_in_buffer = DEST_CHUNK;
    }

    unsafe extern "C-unwind" fn init(cinfo: &mut ffi::jpeg_compress_struct) {
        let this = unsafe { Self::from_cinfo(cinfo) };
        this.out.clear();
        this.grow();
    }

    /// libjpeg calls this with the whole buffer full: everything handed
    /// out is written, so keep it all and add a chunk.
    unsafe extern "C-unwind" fn empty(cinfo: &mut ffi::jpeg_compress_struct) -> ffi::boolean {
        unsafe { Self::from_cinfo(cinfo) }.grow();
        1
    }

    unsafe extern "C-unwind" fn term(cinfo: &mut ffi::jpeg_compress_struct) {
        let this = unsafe { Self::from_cinfo(cinfo) };
        let written = this.out.len() - this.iface.free_in_buffer;
        this.out.truncate(written);
    }
}

/// The coefficient memory rotating by `o` realizes: each component's
/// virtual block array (128 bytes a block, padded to its sampling
/// factors as `jpeg_read_coefficients` allocates it), twice over
/// unless the transform is a horizontal flip, the one transupp does in
/// place (`jtransform_request_workspace`).
fn coefficient_bytes(cinfo: &ffi::jpeg_decompress_struct, o: Orientation) -> u64 {
    let comps = usize::try_from(cinfo.num_components).unwrap_or(0);
    let mut bytes = 0u64;
    for i in 0..comps {
        // SAFETY: jpeg_read_header filled comp_info with num_components
        // entries.
        let c = unsafe { &*cinfo.comp_info.add(i) };
        let round = |n: ffi::JDIMENSION, to: std::os::raw::c_int| {
            let to = u64::try_from(to.max(1)).unwrap_or(1);
            u64::from(n).div_ceil(to) * to
        };
        let blocks = round(c.width_in_blocks, c.h_samp_factor)
            .saturating_mul(round(c.height_in_blocks, c.v_samp_factor));
        bytes = bytes.saturating_add(blocks.saturating_mul(mem::size_of::<ffi::JBLOCK>() as u64));
    }
    if o.value() == 2 {
        bytes
    } else {
        bytes.saturating_mul(2)
    }
}

unsafe fn rotate_unguarded(
    jpeg: &[u8],
    o: Orientation,
    coding: &Coding,
    max_pixels: u64,
) -> Rotation {
    let mut d = Decompress {
        // SAFETY: zeroed with its error manager set, as
        // jpeg_create_decompress requires.
        cinfo: Box::new(unsafe { mem::zeroed() }),
        _err: error_mgr(),
    };
    d.cinfo.common.err = &mut *d._err;
    unsafe {
        ffi::jpeg_create_decompress(&mut *d.cinfo);
        ffi::jpeg_mem_src(&mut d.cinfo, jpeg.as_ptr(), jpeg.len() as c_ulong);
        // APP2 only: the ICC profile. JFIF and Adobe are written by the
        // encoder from the copied parameters; the orientation EXIF is
        // what the rotation makes redundant.
        ffi::jcopy_markers_setup(&mut *d.cinfo, ffi::JCOPY_OPTION_JCOPYOPT_ICC);
        if ffi::jpeg_read_header(&mut d.cinfo, 1) != 1 {
            return Rotation::Kept("no image in the JPEG".into());
        }
    }
    let (w, h) = (d.cinfo.image_width, d.cinfo.image_height);
    if u64::from(w) * u64::from(h) > max_pixels {
        return Rotation::Kept(format!(
            "{w}x{h} is over OXIMG_MAX_SRC_PIXELS ({max_pixels})"
        ));
    }
    // OXIMG_MAX_DECODED_BYTES bounds this as it bounds a decode: the
    // coefficients are realized whole when they are read.
    let cost = super::DecodeCost {
        whole_source_bytes: coefficient_bytes(&d.cinfo, o),
        // The caller's source, the strip's copy of it, and the output.
        compressed_bytes: 3 * jpeg.len() as u64,
        ..Default::default()
    };
    if let Err(e) = super::check_decoded_bytes(cost, "JPEG rotation") {
        return Rotation::Kept(e.to_string());
    }
    // SAFETY: plain C data; zero is "no crop, no trim, all components".
    let mut info = Box::new(Guarded {
        info: unsafe { mem::zeroed() },
        canary: [CANARY; CANARY_LEN],
    });
    info.info.transform = transform_code(o);
    info.info.perfect = 1;
    let perfect = unsafe { ffi::jtransform_request_workspace(&mut *d.cinfo, info.ffi()) };
    assert!(
        info.intact(),
        "jpeg_transform_info overran its declared size"
    );
    if perfect == 0 {
        let (bw, bh) = if d.cinfo.num_components == 1 {
            (8, 8)
        } else {
            (8 * d.cinfo.max_h_samp_factor, 8 * d.cinfo.max_v_samp_factor)
        };
        return Rotation::Kept(format!(
            "{w}x{h} does not divide into whole {bw}x{bh} blocks on the edge \
             orientation {} moves",
            o.value()
        ));
    }
    let src_coefs = unsafe { ffi::jpeg_read_coefficients(&mut d.cinfo) };
    if d._err.num_warnings > 0 {
        return Rotation::Kept("the JPEG data is corrupt or truncated".into());
    }

    let mut c = Compress {
        // SAFETY: as for the decompress struct.
        cinfo: Box::new(unsafe { mem::zeroed() }),
        _err: error_mgr(),
        dest: Box::new(Dest {
            iface: ffi::jpeg_destination_mgr {
                next_output_byte: std::ptr::null_mut(),
                free_in_buffer: 0,
                init_destination: Some(Dest::init),
                empty_output_buffer: Some(Dest::empty),
                term_destination: Some(Dest::term),
            },
            out: Vec::with_capacity(jpeg.len() + DEST_CHUNK),
        }),
    };
    c.cinfo.common.err = &mut *c._err;
    unsafe {
        ffi::jpeg_create_compress(&mut *c.cinfo);
        // libjpeg's defaults, not mozjpeg's: these are set inside
        // jpeg_copy_critical_parameters, and mozjpeg's own would make
        // every output progressive with a searched scan script.
        ffi::jpeg_c_set_int_param(
            &mut c.cinfo,
            ffi::J_INT_PARAM::JINT_COMPRESS_PROFILE,
            ffi::JCP_FASTEST as c_int,
        );
        ffi::jpeg_copy_critical_parameters(&d.cinfo, &mut c.cinfo);
        let dst_coefs =
            ffi::jtransform_adjust_parameters(&mut *d.cinfo, &mut *c.cinfo, src_coefs, info.ffi());
        // Huffman tables are rebuilt for the moved blocks either way;
        // optimal ones cost a second pass over memory, not quality.
        c.cinfo.optimize_coding = 1;
        if coding.progressive {
            ffi::jpeg_simple_progression(&mut c.cinfo);
        }
        c.cinfo.write_JFIF_header = coding.jfif as ffi::boolean;
        if o.swaps_axes() {
            // transupp swaps the dimensions, not the pixel aspect.
            mem::swap(&mut c.cinfo.X_density, &mut c.cinfo.Y_density);
        }
        c.cinfo.dest = &mut c.dest.iface;
        ffi::jpeg_write_coefficients(&mut c.cinfo, dst_coefs);
        ffi::jcopy_markers_execute(&mut *d.cinfo, &mut *c.cinfo, ffi::JCOPY_OPTION_JCOPYOPT_ICC);
        ffi::jtransform_execute_transform(&mut *d.cinfo, &mut *c.cinfo, src_coefs, info.ffi());
        ffi::jpeg_finish_compress(&mut c.cinfo);
        ffi::jpeg_finish_decompress(&mut d.cinfo);
    }
    assert!(
        info.intact(),
        "jpeg_transform_info overran its declared size"
    );
    if d._err.num_warnings > 0 {
        return Rotation::Kept("the JPEG data is corrupt or truncated".into());
    }
    Rotation::Rotated(mem::take(&mut c.dest.out))
}

#[cfg(test)]
mod tests {
    use super::*;

    const BASELINE: Coding = Coding {
        progressive: false,
        jfif: true,
    };

    fn jpeg(w: usize, h: usize) -> Vec<u8> {
        let mut comp = mozjpeg::Compress::new(mozjpeg::ColorSpace::JCS_RGB);
        comp.set_fastest_defaults(); // baseline SOF0
        comp.set_size(w, h);
        let mut started = comp.start_compress(Vec::new()).unwrap();
        started.write_scanlines(&vec![128u8; w * h * 3]).unwrap();
        started.finish().unwrap()
    }

    /// Orientation 6, through the parser (the field is private to meta).
    fn six() -> Orientation {
        let tiff = b"MM\0\x2a\0\0\0\x08\0\x01\x01\x12\0\x03\0\0\0\x01\0\x06\0\0\0\0\0\0";
        Orientation::from_exif_payload(tiff).unwrap()
    }

    fn kept(r: Rotation) -> String {
        match r {
            Rotation::Kept(why) => why,
            Rotation::Rotated(_) => panic!("rotated"),
        }
    }

    #[test]
    fn the_source_pixel_limit_bounds_the_coefficient_memory() {
        let six = six();
        let src = jpeg(64, 48);
        let why = kept(rotate(&src, six, &BASELINE, 64 * 48 - 1));
        assert!(
            why.contains("64x48") && why.contains("OXIMG_MAX_SRC_PIXELS"),
            "{why}"
        );
        assert!(matches!(
            rotate(&src, six, &BASELINE, 64 * 48),
            Rotation::Rotated(_)
        ));
    }

    /// transupp writes fields past the end of mozjpeg-sys's
    /// `jpeg_transform_info` (the iMCU size, here 16x16 for 4:2:0):
    /// declared with that binding, they landed on whatever followed it
    /// (a progressive source was then written baseline in one CI build).
    /// They land in this struct, and the canary after it is untouched.
    #[test]
    fn transupp_writes_land_inside_the_declared_struct() {
        let src = jpeg(64, 48);
        assert!(
            mem::offset_of!(TransformInfo, i_mcu_sample_width)
                >= mem::size_of::<ffi::jpeg_transform_info>(),
            "the binding grew: drop this struct for it"
        );
        let mut d = Decompress {
            cinfo: Box::new(unsafe { mem::zeroed() }),
            _err: error_mgr(),
        };
        d.cinfo.common.err = &mut *d._err;
        let mut info = Box::new(Guarded {
            info: unsafe { mem::zeroed() },
            canary: [CANARY; CANARY_LEN],
        });
        info.info.transform = ffi::JXFORM_CODE_JXFORM_ROT_90;
        info.info.perfect = 1;
        let perfect = unsafe {
            ffi::jpeg_create_decompress(&mut *d.cinfo);
            ffi::jpeg_mem_src(&mut d.cinfo, src.as_ptr(), src.len() as c_ulong);
            assert_eq!(ffi::jpeg_read_header(&mut d.cinfo, 1), 1);
            ffi::jtransform_request_workspace(&mut *d.cinfo, info.ffi())
        };
        assert_eq!(perfect, 1);
        assert_eq!(
            (info.info.i_mcu_sample_width, info.info.i_mcu_sample_height),
            (16, 16)
        );
        assert_eq!((info.info.output_width, info.info.output_height), (48, 64));
        assert!(info.intact());
    }

    /// A fatal libjpeg error is a reason to keep the tag, not a failed
    /// strip: the strip itself copied the file without decoding it.
    #[test]
    fn a_stream_libjpeg_cannot_read_is_kept() {
        let six = six();
        let mut src = jpeg(64, 48);
        // SOF0 -> SOF3 (lossless), which this libjpeg build cannot read.
        let sof = src.windows(2).position(|w| w == [0xFF, 0xC0]).unwrap();
        src[sof + 1] = 0xC3;
        let why = kept(rotate(&src, six, &BASELINE, u64::MAX));
        assert!(why.contains("libjpeg"), "{why}");
        assert!(kept(rotate(b"\xFF\xD8", six, &BASELINE, u64::MAX)).contains("libjpeg"));
    }
}
